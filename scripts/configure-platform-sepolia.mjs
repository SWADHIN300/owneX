import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const rootEnvFile = join(root, ".env");
const deploymentFile = join(root, "deployments", "sepolia.json");
const envFile = join(root, "apps", "platform", ".env.local");

if (!existsSync(deploymentFile)) {
  throw new Error("No deployments/sepolia.json found. Run npm run deploy:sepolia first.");
}

if (!existsSync(envFile)) {
  throw new Error("No apps/platform/.env.local found. Copy apps/platform/.env.local.example first.");
}

const deployment = JSON.parse(readFileSync(deploymentFile, "utf8"));
const current = parseEnv(readFileSync(envFile, "utf8"));
const rootEnv = existsSync(rootEnvFile) ? parseEnv(readFileSync(rootEnvFile, "utf8")) : new Map();

const next = new Map(current);
preserveLocal(next, current, "RPC_URL");
preserveLocal(next, current, "CHAIN_ID");
preserveLocal(next, current, "IDENTITY_REGISTRY_ADDRESS");
preserveLocal(next, current, "ORG_ACCESS_MANAGER_ADDRESS");
preserveLocal(next, current, "ASSET_NFT_ADDRESS");
preserveLocal(next, current, "NEXT_PUBLIC_CHAIN_ID");
preserveLocal(next, current, "NEXT_PUBLIC_CHAIN_NAME");
preserveLocal(next, current, "NEXT_PUBLIC_IDENTITY_REGISTRY_ADDRESS");
preserveLocal(next, current, "NEXT_PUBLIC_ORG_ACCESS_MANAGER_ADDRESS");
preserveLocal(next, current, "NEXT_PUBLIC_ASSET_NFT_ADDRESS");

const publicRpc = rootEnv.get("NEXT_PUBLIC_RPC_URL") || "https://rpc.sepolia.org";

next.set("RPC_URL", rootEnv.get("SEPOLIA_RPC_URL") || "https://rpc.sepolia.org");
next.set("CHAIN_ID", "11155111");
next.set("IDENTITY_REGISTRY_ADDRESS", deployment.contracts.IdentityRegistry);
next.set("ORG_ACCESS_MANAGER_ADDRESS", deployment.contracts.OrgAccessManager);
next.set("ASSET_NFT_ADDRESS", deployment.contracts.AssetNFT);
next.set("NEXT_PUBLIC_CHAIN_ID", "11155111");
next.set("NEXT_PUBLIC_CHAIN_NAME", "Sepolia");
next.set("NEXT_PUBLIC_RPC_URL", publicRpc);
next.set("NEXT_PUBLIC_EXPLORER_URL", "https://sepolia.etherscan.io");
next.set("NEXT_PUBLIC_IDENTITY_REGISTRY_ADDRESS", deployment.contracts.IdentityRegistry);
next.set("NEXT_PUBLIC_ORG_ACCESS_MANAGER_ADDRESS", deployment.contracts.OrgAccessManager);
next.set("NEXT_PUBLIC_ASSET_NFT_ADDRESS", deployment.contracts.AssetNFT);

writeFileSync(envFile, `${formatEnv(next)}\n`);

console.log("apps/platform/.env.local now points at Sepolia.");
console.log(`IdentityRegistry  ${deployment.contracts.IdentityRegistry}`);
console.log(`OrgAccessManager  ${deployment.contracts.OrgAccessManager}`);
console.log(`AssetNFT          ${deployment.contracts.AssetNFT}`);

function parseEnv(source) {
  const map = new Map();
  for (const line of source.split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith("#") || !line.includes("=")) continue;
    const index = line.indexOf("=");
    map.set(line.slice(0, index).trim(), line.slice(index + 1).trim());
  }
  return map;
}

function preserveLocal(next, current, key) {
  const value = current.get(key);
  if (!value) return;
  if (String(value) === "11155111" || String(value).includes("sepolia")) return;
  if (/^0x[a-fA-F0-9]{40}$/.test(value) || value.includes("127.0.0.1") || value === "31337" || value === "Hardhat Local") {
    next.set(`LOCAL_${key}`, value);
  }
}

function formatEnv(map) {
  const sections = [
    ["Supabase", ["SUPABASE_URL", "SUPABASE_SERVICE_ROLE_KEY", "NEXT_PUBLIC_SUPABASE_URL", "NEXT_PUBLIC_SUPABASE_ANON_KEY"]],
    ["Sepolia chain", ["RPC_URL", "CHAIN_ID", "IDENTITY_REGISTRY_ADDRESS", "ORG_ACCESS_MANAGER_ADDRESS", "ASSET_NFT_ADDRESS"]],
    ["Auth", ["SESSION_PASSWORD", "PII_ENCRYPTION_KEY", "APP_DOMAIN", "APP_ORIGIN"]],
    ["Public browser config", ["NEXT_PUBLIC_CHAIN_ID", "NEXT_PUBLIC_CHAIN_NAME", "NEXT_PUBLIC_RPC_URL", "NEXT_PUBLIC_EXPLORER_URL", "NEXT_PUBLIC_IDENTITY_REGISTRY_ADDRESS", "NEXT_PUBLIC_ORG_ACCESS_MANAGER_ADDRESS", "NEXT_PUBLIC_ASSET_NFT_ADDRESS"]],
    ["Recoverable local chain values", [...map.keys()].filter((key) => key.startsWith("LOCAL_")).sort()],
  ];

  const emitted = new Set();
  const lines = ["# Generated by npm run config:platform:sepolia", "# apps/platform/.env.local is gitignored. Never commit real values."];
  for (const [title, keys] of sections) {
    lines.push("", `# ${title}`);
    for (const key of keys) {
      if (!map.has(key)) continue;
      emitted.add(key);
      lines.push(`${key}=${map.get(key)}`);
    }
  }

  const rest = [...map.keys()].filter((key) => !emitted.has(key)).sort();
  if (rest.length > 0) {
    lines.push("", "# Other preserved values");
    for (const key of rest) lines.push(`${key}=${map.get(key)}`);
  }

  return lines.join("\n");
}
